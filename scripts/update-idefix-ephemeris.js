const fs = require('node:fs');
const path = require('node:path');
const endpoint = 'https://ssd.jpl.nasa.gov/api/horizons.api';

/**
 * Downloads heliocentric geometric MMX positions from the public JPL Horizons API.
 * @param {string} start UTC calendar start.
 * @param {string} stop UTC calendar stop.
 * @param {string} step Horizons time interval.
 * @returns {Promise<{url:string,result:string}>} Query provenance and Horizons text.
 */
async function downloadVectors(start, stop, step){
  const parameters = {
    format:'json', COMMAND:"'-239'", EPHEM_TYPE:"'VECTORS'", CENTER:"'500@10'",
    START_TIME:"'" + start + "'", STOP_TIME:"'" + stop + "'", STEP_SIZE:"'" + step + "'",
    VEC_TABLE:"'1'", REF_PLANE:"'ECLIPTIC'", REF_SYSTEM:"'ICRF'", OUT_UNITS:"'AU-D'",
    VEC_CORR:"'NONE'", TIME_TYPE:"'UT'", CSV_FORMAT:"'YES'", OBJ_DATA:"'YES'"
  };
  const url = endpoint + '?' + new URLSearchParams(parameters).toString();
  const response = await fetch(url, {signal:AbortSignal.timeout(45000)});
  if (!response.ok) {
    throw new Error('Horizons HTTP ' + response.status);
  }
  const payload = await response.json();
  if (!payload.signature || payload.signature.version !== '1.2') {
    throw new Error('Unexpected Horizons API version; inspect the response before importing.');
  }
  if (payload.error || !payload.result || !payload.result.includes('$$SOE')) {
    throw new Error(payload.error || payload.result || 'Missing vector table');
  }
  if (!payload.result.includes('MMX') || !payload.result.includes('Ecliptic of J2000.0')) {
    throw new Error('Unexpected target or reference frame');
  }
  return {url, result:payload.result};
}

/**
 * Parses UTC Julian dates and AU vectors from a Horizons CSV vector table.
 * @param {string} result Full Horizons response text.
 * @returns {number[][]} Rows [UTC Unix milliseconds, xAU, yAU, zAU].
 */
function parseVectors(result){
  const body = result.split('$$SOE')[1].split('$$EOE')[0].trim();
  return body.split(/\r?\n/).filter(line => line.trim()).map(line => {
    const fields = line.split(',').map(field => field.trim());
    const julianDate = Number(fields[0]);
    const vector = [Number(fields[2]), Number(fields[3]), Number(fields[4])];
    if (!Number.isFinite(julianDate) || !vector.every(Number.isFinite)) {
      throw new Error('Invalid Horizons vector row');
    }
    const timestamp = Math.round((julianDate - 2440587.5) * 86400000);
    return [timestamp, ...vector.map(value => Number(value.toFixed(12)))];
  });
}

/** Downloads and validates a planning snapshot before replacing the browser data file. No parameters. @returns {Promise<void>} */
async function main(){
  // Dense first-week points improve the departure display. Subsequent daily samples
  // are for the heliocentric overview, not local Mars/Phobos navigation.
  const first = await downloadVectors('2026-10-19 21:00', '2026-10-26 21:00', '6 h');
  const rest = await downloadVectors('2026-10-26 21:00', '2028-12-31 00:00', '1 d');
  if (!first.result.includes('Pre-launch planning trajectory from JAXA') || !first.result.includes('20261019_20281231_MMX_V0.2')) {
    throw new Error('The JAXA solution has changed; review provenance and update configuration before importing.');
  }
  const revisedMatch = first.result.match(/Revised:\s*([A-Za-z]+\s+\d{1,2},\s+\d{4})/);
  if (!revisedMatch) {
    throw new Error('Missing JPL revision date');
  }
  const revised = new Date(revisedMatch[1] + ' UTC').toISOString().slice(0, 10);
  const rows = [...parseVectors(first.result), ...parseVectors(rest.result).slice(1)];
  if (rows.length < 800 || rows[0][0] !== Date.parse('2026-10-19T21:00:00Z') || rows[rows.length - 1][0] < Date.parse('2028-12-30T21:00:00Z')) {
    throw new Error('Incomplete or unexpectedly timed ephemeris; original data kept.');
  }
  for (let index = 1; index < rows.length; index += 1) {
    if (rows[index][0] <= rows[index - 1][0]) {
      throw new Error('Non-monotonic trajectory timestamps');
    }
  }
  const data = {
    source:'NASA/JPL Horizons · JAXA pre-launch planning trajectory',
    spacecraftId:-239,
    trajectory:'20261019_20281231_MMX_V0.2',
    revised,
    retrievedAt:new Date().toISOString(),
    type:'prediction',
    frame:'Ecliptic of J2000.0 / ICRF, heliocentric geometric vectors',
    timeScale:'UTC',
    units:'AU',
    interpolation:'linear',
    queryUrls:[first.url, rest.url],
    start:new Date(rows[0][0]).toISOString(),
    end:new Date(rows[rows.length - 1][0]).toISOString(),
    rows
  };
  const output = path.resolve(__dirname, '..', 'idefix-ephemeris.js');
  const header = '/** JPL/JAXA planning vectors, not live telemetry. Generated by scripts/update-idefix-ephemeris.js. */\n';
  fs.writeFileSync(output, header + 'window.PLANETENUHR_IDEFIX_EPHEMERIS = ' + JSON.stringify(data) + ';\n', 'utf8');
  console.log(JSON.stringify({samples:rows.length,start:data.start,end:data.end,trajectory:data.trajectory,output},null,2));
}

/** Reports a failed download without replacing validated data. @param {Error} error Failure. @returns {void} */
function reportFailure(error){
  console.error(error.message);
  process.exitCode = 1;
}
if (require.main === module) {
  main().catch(reportFailure);
}

module.exports = {parseVectors};
